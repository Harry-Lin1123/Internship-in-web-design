    $(document).ready(function () {
        // 捲軸偵測距離頂部超過 50 才顯示按鈕
        $(window).scroll(function () {
          if ($(window).scrollTop() > 50) {
            if ($(".back-top2").hasClass("hide")) {
              $(".back-top2").toggleClass("hide");
            }
          } else {
            $(".back-top2").addClass("hide");
          }
        });
      
        // 點擊按鈕回頂部
        $(".back-top2").on("click", function (event) {
          $("html, body").animate(
            {
              scrollTop: 550
            },
            500 // 回頂部時間為 500 毫秒
          );
        });
      });
